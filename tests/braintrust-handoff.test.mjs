import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {mountBraintrustImport} from '../public/app/braintrust-import.js';
import {normalizeBraintrustScope} from '../public/app/braintrust-scope.js';
import {planBraintrustCapture} from '../src/importers/braintrust-capture.mjs';
import {spec} from './braintrust-fixtures.mjs';

test('browser scope contract is the exact generated runtime contract', () => {
  assert.equal(readFileSync(new URL('../public/app/braintrust-scope.js', import.meta.url), 'utf8'), '// Generated by scripts/sync-braintrust-scope.mjs; do not edit.\n' + readFileSync(new URL('../src/importers/braintrust-scope.mjs', import.meta.url), 'utf8'));
  assert.deepEqual(normalizeBraintrustScope(spec), planBraintrustCapture(spec).scope);
});

function fixture(options = {}) {
  const nodes = new Map(), get = id => { if (!nodes.has(id)) nodes.set(id, {value: '', checked: false, hidden: false, disabled: false, textContent: ''}); return nodes.get(id); };
  let project = spec.destinationProject;
  for (const [key, value] of Object.entries({origin: spec.origin, source: spec.sourceProject, namespace: spec.namespace, roots: spec.rootSpanIds.join('\n'), rows: '1000', pages: '100', 'page-size': '100'})) get('braintrust-' + key).value = value;
  const downloads = [], copied = [];
  const ui = mountBraintrustImport({document: {getElementById: get}, getProject: () => project, download: (blob, name) => downloads.push({blob, name}), clipboard: {writeText: async value => copied.push(value)}, ...options});
  return {get, downloads, copied, ui, setProject: value => {project = value;}, review: () => get('braintrust-form').onsubmit({preventDefault() {}}), approve: () => {get('braintrust-reviewed').checked = true; get('braintrust-reviewed').onchange();}};
}

test('review produces an importer-valid metadata spec; download/copy require explicit review', async () => {
  const f = fixture(); f.review();
  assert.equal(f.get('braintrust-download').disabled, true);
  f.get('braintrust-download').onclick(); assert.equal(f.downloads.length, 0);
  f.approve(); f.get('braintrust-download').onclick();
  const saved = JSON.parse(await f.downloads[0].blob.text());
  assert.equal(f.downloads[0].name, 'braintrust-import.json');
  assert.deepEqual(saved, planBraintrustCapture(saved).scope);
  assert.equal(saved.content, 'metadata'); assert.equal(saved.destinationProject, spec.destinationProject);
  assert.doesNotMatch(f.get('braintrust-command').textContent, /--include-content/);
  await f.get('braintrust-copy').onclick(); assert.deepEqual(JSON.parse(f.copied[0]), saved);
});

test('content opt-in is reflected in both JSON and the executable command', () => {
  const f = fixture(); f.get('braintrust-content').checked = true; f.review();
  assert.equal(JSON.parse(f.get('braintrust-spec').textContent).content, 'include');
  assert.match(f.get('braintrust-command').textContent, /--include-content$/);
  f.get('braintrust-form').oninput();
  assert.equal(f.get('braintrust-output').hidden, true); assert.equal(f.get('braintrust-reviewed').checked, false);
});

test('invalid and oversized scopes clear stale output without echoing untrusted fields', () => {
  for (const [id, value] of [['source', '<script>PRIVATE</script>'], ['roots', 'duplicate\nduplicate'], ['roots', Array.from({length: 26}, (_, i) => 'root-' + i).join('\n')], ['rows', '1001'], ['page-size', '0'], ['namespace', 'PRIVATE/unsafe']]) {
    const f = fixture(); f.review(); f.approve(); f.get('braintrust-' + id).value = value; f.review();
    assert.equal(f.get('braintrust-output').hidden, true); assert.equal(f.get('braintrust-download').disabled, true);
    assert.equal(f.get('braintrust-spec').textContent, ''); assert.doesNotMatch(f.get('braintrust-status').textContent, /PRIVATE/);
  }
});

test('workspace change, sign-out and pause invalidate a reviewed artifact', async () => {
  for (const next of [null, 'proj_' + 'a'.repeat(32)]) {
    const f = fixture(); f.review(); f.approve(); f.setProject(next);
    f.get('braintrust-download').onclick(); await f.get('braintrust-copy').onclick();
    assert.equal(f.downloads.length, 0); assert.equal(f.copied.length, 0); assert.equal(f.get('braintrust-output').hidden, true);
  }
  const f = fixture(); f.review(); f.approve(); f.ui.invalidate();
  assert.equal(f.get('braintrust-spec').textContent, ''); assert.equal(f.get('braintrust-command').textContent, '');
});

test('clipboard failure and an old completion cannot misrepresent the current review', async () => {
  let finish;
  const f = fixture({clipboard: {writeText: () => new Promise(resolve => {finish = resolve;})}});
  f.review(); f.approve(); const pending = f.get('braintrust-copy').onclick(); f.ui.invalidate(); finish(); await pending;
  assert.equal(f.get('braintrust-status').textContent, 'Scope changed. Review it again before downloading.');
  const rejected = fixture({clipboard: {writeText: async () => {throw Error('PRIVATE');}}});
  rejected.review(); rejected.approve(); await rejected.get('braintrust-copy').onclick();
  assert.match(rejected.get('braintrust-status').textContent, /Clipboard unavailable/);
  assert.doesNotMatch(rejected.get('braintrust-status').textContent, /PRIVATE/);
});
