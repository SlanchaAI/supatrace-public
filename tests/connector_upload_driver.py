"""Synthetic harness only: map the retained HTTPS transport to explicit loopback.
Never called by product source. Credentials are generated by tests in memory.
"""
import io
import json
import sys
import time
import urllib.request
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'agent'))
from private_upload_runtime import upload_staged_workspace

config = json.load(sys.stdin)
assert config['local_origin'].startswith('http://127.0.0.1:')
scope = config['scope']

class Response:
    def __init__(self, url, status, body):
        self.url, self.status, self.body = url, status, io.BytesIO(body)
    def geturl(self): return self.url
    def __enter__(self): return self
    def __exit__(self, *args): self.close()
    def read(self, length): return self.body.read(length)
    def close(self): self.body.close()

def transport(request, timeout):
    if config.get('failure') == 'rate_limit':
        return Response(request.full_url, 429, b'{"error":"rate_limit"}')
    local_url = config['local_origin'] + request.full_url.removeprefix(scope['origin'])
    local = urllib.request.Request(local_url, data=request.data, headers=dict(request.header_items()), method='POST')
    with urllib.request.urlopen(local, timeout=timeout) as response:
        body = response.read(8193)
        if config.get('failure') == 'lost_ack': raise OSError('synthetic_lost_ack')
        return Response(request.full_url, response.status, body)

result = upload_staged_workspace(config['directory'], scope,
    credential_provider=lambda _: {'origin': scope['origin'], 'project_id': scope['project_id'], 'write_key': config['key'], 'expires_at': time.time() + 120},
    authorize=lambda _: True, transport=transport)
print(json.dumps(result))
